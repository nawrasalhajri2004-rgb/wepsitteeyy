function updateTeacherReport() {
    const tbody = document.getElementById('reportTableBody');
    tbody.innerHTML = '<tr><td colspan="4">جَارِي تَحْمِيلِ بَيَانَاتِ الطُّلَّابِ مِنَ السَّحَابَةِ...</td></tr>';

    db.collection("students").get().then((querySnapshot) => {
        if (querySnapshot.empty) {
            tbody.innerHTML = '<tr><td colspan="4">لَمْ يُسَجِّلْ أَيُّ طَالِبٍ دُخُولَهُ حَتَّى الآنَ</td></tr>';
            return;
        }

        tbody.innerHTML = "";
        querySnapshot.forEach((doc) => {
            const s = doc.data();
            const key = doc.id;
            const readCount = s.progress ? Object.keys(s.progress).length : 0;
            
            tbody.innerHTML += `
                <tr>
                    <td><strong>${s.name}</strong></td>
                    <td>${s.className}</td>
                    <td><span style="color: #059669; font-weight: 700;">${readCount} / 30 قصة</span></td>
                    <td><button class="btn btn-audio" style="padding: 6px 12px; font-size: 0.9rem; margin: 0 auto;" onclick="viewStudentDetails('${key}')">عَرْضُ حَالَةِ القِرَاءَةِ 📋</button></td>
                </tr>
            `;
        });
    }).catch((error) => {
        tbody.innerHTML = `<tr><td colspan="4" style="color:red;">خطأ في الاتصال بقاعدة البيانات: تأكد من تفعيل Firestore في وضع الاختبار.</td></tr>`;
    });
}

