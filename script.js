function checkStudentData() {
    const studentId = localStorage.getItem('currentStudentId');
    if (studentId) {
        document.getElementById('studentModal').classList.add('hidden');
        db.collection("students").doc(studentId).get().then((doc) => {
            if (doc.exists) {
                const student = doc.data();
                document.getElementById('welcomeTag').innerText = `مَرْحَباً بِكَ يَا بَطَلُ: ${student.name} (${student.className})`;
            }
        }).catch(() => {});
    } else {
        document.getElementById('studentModal').classList.remove('hidden');
    }
}

function saveStudentInfo() {
    const name = document.getElementById('studentNameInput').value.trim();
    const studentClass = document.getElementById('studentClassInput').value.trim();

    if (name === "" || studentClass === "") {
        alert("فَضْلاً يَا بَطَلُ، اكْتُبِ الاِسْمَ الكَرِيمَ وَالصَّفَّ كَامِلاً!");
        return;
    }

    const studentId = name.replace(/\s+/g, '_') + "_" + studentClass.replace(/\s+/g, '_');
    localStorage.setItem('currentStudentId', studentId);

    db.collection("students").doc(studentId).set({
        name: name,
        className: studentClass,
        progress: {}
    }, { merge: true }).then(() => {
        checkStudentData();
        renderStories();
        updateRewards();
    }).catch((error) => {
        console.error("Error saving student: ", error);
        checkStudentData();
        renderStories();
        updateRewards();
    });
}

function renderStories() {
    const container = document.getElementById('storiesContainer');
    const studentId = localStorage.getItem('currentStudentId');

    // عرض القصص محلياً فوراً لضمان ظهور البطاقات دائماً
    db.collection("students").doc(studentId || "guest").get().then((doc) => {
        const progress = doc.exists ? (doc.data().progress || {}) : {};
        
        container.innerHTML = stories.map(story => {
            const isRead = progress[story.id] !== undefined;
            const score = isRead ? progress[story.id].score : 0;
            const total = story.questions.length;

            return `
                <div class="story-btn" onclick="openStory('${story.id}')">
                    <span class="icon">${story.icon}</span>
                    <h3>${story.title}</h3>
                    <span class="status-badge ${isRead ? 'badge-read' : 'badge-unread'}">
                        ${isRead ? `تم الإنجاز (${score}/${total})` : 'لَمْ تُقْرَأْ بَعْدُ'}
                    </span>
                </div>
            `;
        }).join('');
    }).catch(() => {
        // Fallback إذا لم يتصل بقاعدة البيانات فوريأً
        container.innerHTML = stories.map(story => `
            <div class="story-btn" onclick="openStory('${story.id}')">
                <span class="icon">${story.icon}</span>
                <h3>${story.title}</h3>
                <span class="status-badge badge-unread">لَمْ تُقْرَأْ بَعْدُ</span>
            </div>
        `).join('');
    });
}

function updateRewards() {
    const studentId = localStorage.getItem('currentStudentId');
    if (!studentId) return;

    db.collection("students").doc(studentId).get().then((doc) => {
        const progress = doc.exists ? (doc.data().progress || {}) : {};
        const readCount = Object.keys(progress).length;
        const totalStories = stories.length;
        const percentage = (readCount / totalStories) * 100;

        document.getElementById('progressText').innerText = `أَكْمَلْتَ ${readCount} مِنْ ${totalStories} قِصَّةً بِبَرَاعَةٍ`;
        document.getElementById('progressBar').style.width = `${percentage}%`;

        if (readCount >= 10) document.getElementById('badge1').classList.add('unlocked');
        if (readCount >= 20) document.getElementById('badge2').classList.add('unlocked');
        if (readCount >= 30) document.getElementById('badge3').classList.add('unlocked');
    }).catch(() => {});
}

